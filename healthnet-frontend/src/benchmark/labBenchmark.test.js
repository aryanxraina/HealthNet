import fs from 'fs';
import path from 'path';
import { parseLabReport } from '../ocr/labParser';
import TAGGER from '../ocr/tagger/model.json';
import { sectionById } from '../questionnaire/sections';
import { generateLabReports, LAYOUTS } from './synthLabReports';
import { scoreReader } from './scoreLab';

// Lab report reading benchmark (R0 and R2 in docs/on-device-model-roadmap.md).
//
// Every test run scores each reader on the synthetic test set and fails if one got worse than its
// committed baseline: lower F1, or more dangerous errors. After a deliberate improvement, run
// `npm run benchmark` to record new baselines and rewrite docs/benchmarks/lab-reports.md.

const TEST_SEED = 20261025;
const TEST_DOCUMENTS = 600;
const SLACK = 0.002;
const BASELINES = path.join(__dirname, 'baselines');
const REPORT = path.join(__dirname, '..', '..', '..', 'docs', 'benchmarks', 'lab-reports.md');

// The app ships 'tagger' (rules first, the Tagger for lines the rules can't place)
const READERS = {
  rules: { title: 'Rules only', read: (lines) => parseLabReport(lines) },
  tagger: { title: 'Rules + Tagger (shipped)', read: (lines) => parseLabReport(lines, { tagger: TAGGER }) },
};

const documents = generateLabReports(TEST_SEED, TEST_DOCUMENTS);

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const table = (rows) =>
  ['| | Values | Precision | Recall | F1 | Dangerous error rate | Documents with a dangerous error |', '|---|---|---|---|---|---|---|']
    .concat(Object.entries(rows).map(([name, s]) => `| ${name} | ${s.values} | ${pct(s.precision)} | ${pct(s.recall)} | ${pct(s.f1)} | ${pct(s.dangerousErrorRate)} | ${s.documents ? pct(s.documentsWithDangerousError) : '–'} |`))
    .join('\n');

const byFieldComparison = (results) => {
  const fields = Object.keys(results.tagger.byField);
  return ['| Test | Rules recall | Rules + Tagger recall | Rules + Tagger precision |', '|---|---|---|---|']
    .concat(fields.map((field) => `| ${field} | ${pct(results.rules.byField[field].recall)} | ${pct(results.tagger.byField[field].recall)} | ${pct(results.tagger.byField[field].precision)} |`))
    .join('\n');
};

const report = (results, speed) => {
  const shipped = results.tagger;
  return `# Lab report reading benchmark

<!-- Generated by \`npm run benchmark\` (healthnet-frontend/src/benchmark/labBenchmark.test.js). Don't edit by hand. -->

**Test set:** ${TEST_DOCUMENTS} synthetic lab reports, seed ${TEST_SEED} (\`src/benchmark/synthLabReports.js\`) · **Speed** (parsing only, on the machine that ran the benchmark; on-device OCR not included): rules ${speed.rules.toFixed(2)} ms per report, rules + Tagger ${speed.tagger.toFixed(2)} ms

The documents are made up: random values in ${LAYOUTS.length} real-world layouts, with look-alike tests (LDL, eAG, post-prandial glucose, ratios) that must not be read, header lines full of other numbers, and OCR-style noise on half of them. Test names and units are written independently of the parser's dictionary, so names it doesn't know count against it. None of the test names was in the Tagger's training data; the ones the rules can't place were kept out even inside longer names.

- **Correct** means the value is within the rounding of the printed number, with any required flag (plain "Glucose" must be flagged as possibly not fasting).
- **Dangerous error** means a wrong value that the review screen pre-ticks (in range, confidence ≥ 0.5), so one click would save it.

## Readers compared

${table(Object.fromEntries(Object.entries(READERS).map(([id, { title }]) => [title, results[id].overall])))}

## By test

${byFieldComparison(results)}

## Rules + Tagger in detail

### By layout

${table(shipped.byLayout)}

### By noise

${table(shipped.byNoise)}

### Error types

| Missed | Wrong value | Not on the report (false positive) | Missing "not fasting" flag |
|---|---|---|---|
| ${shipped.errors.missed} | ${shipped.errors.wrongValue} | ${shipped.errors.falsePositive} | ${shipped.errors.missingFlag} |

### Confidence calibration

| Confidence | Items | Share correct |
|---|---|---|
${shipped.calibration.map((b) => `| ${b.confidence} | ${b.items} | ${b.accuracy === null ? '–' : pct(b.accuracy)} |`).join('\n')}

### Examples of dangerous errors

| Layout | Noise | Test | Read | Expected | Source text |
|---|---|---|---|---|---|
${shipped.dangerousExamples.slice(0, 12).map((e) => `| ${e.layout} | ${e.noise} | ${e.field} | ${e.read} | ${e.expected ?? 'not on report'} | \`${String(e.sourceText).replace(/\|/g, '\\|')}\` |`).join('\n')}
`;
};

test('synthetic documents are reproducible and plausible', () => {
  expect(generateLabReports(7, 3)).toEqual(generateLabReports(7, 3));
  const vitals = sectionById('vitals').questions;
  documents.forEach((document) => {
    Object.entries(document.truth).forEach(([field, { value }]) => {
      const question = vitals.find((q) => q.id === field);
      expect(value).toBeGreaterThanOrEqual(question.min);
      expect(value).toBeLessThanOrEqual(question.max);
    });
  });
  expect(new Set(documents.map((d) => d.layout))).toEqual(new Set(LAYOUTS));
});

test('no lab report reader gets worse than its baseline', () => {
  const results = {};
  const speed = {};
  Object.entries(READERS).forEach(([id, { read }]) => {
    const started = performance.now();
    documents.forEach((document) => read(document.lines));
    speed[id] = (performance.now() - started) / documents.length;
    results[id] = scoreReader(read, documents);
  });

  if (process.env.BENCHMARK_UPDATE) {
    fs.mkdirSync(BASELINES, { recursive: true });
    Object.entries(results).forEach(([id, result]) => {
      const baseline = { seed: TEST_SEED, documents: TEST_DOCUMENTS, overall: result.overall, byLayout: result.byLayout, byNoise: result.byNoise };
      fs.writeFileSync(path.join(BASELINES, `lab-${id}.json`), `${JSON.stringify(baseline, null, 2)}\n`);
    });
    fs.mkdirSync(path.dirname(REPORT), { recursive: true });
    fs.writeFileSync(REPORT, report(results, speed));
  }

  Object.entries(results).forEach(([id, result]) => {
    const baseline = JSON.parse(fs.readFileSync(path.join(BASELINES, `lab-${id}.json`), 'utf8'));
    expect(result.overall.f1).toBeGreaterThanOrEqual(baseline.overall.f1 - SLACK);
    expect(result.overall.dangerousErrorRate).toBeLessThanOrEqual(baseline.overall.dangerousErrorRate + SLACK);
  });
  // The shipped reader must beat the rules alone without adding dangerous errors (R2 exit criterion)
  expect(results.tagger.overall.f1).toBeGreaterThan(results.rules.overall.f1);
  expect(results.tagger.overall.dangerousErrorRate).toBeLessThanOrEqual(results.rules.overall.dangerousErrorRate + SLACK);
});
